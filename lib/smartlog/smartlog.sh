#!/bin/bash
##############################################################################
# Smartlog v 1.0
##############################################################################

set -e



##############################################################################
# Color definitions.
##############################################################################
BOLD=`tput bold`
ULINE=`tput smul`
NOLINE=`tput rmul`
RED=`tput setaf 1`
GREEN=`tput setaf 2`
YELLOW=`tput setaf 3`
BLUE=`tput setaf 4`
PURPLE=`tput setaf 5`
NORMAL=`tput sgr0`



##############################################################################
# Print abort message and exit.
##############################################################################
die() {
	if [  "$QUIET" != "true"  ]
	then
		abort "$1"
		echo ""
	fi
	exit 1
}



##############################################################################
# Print alert message, help message and exit.
##############################################################################
error() {
	if [  "$QUIET" != "true"  ]
	then
		alert "$1"
		tip "Check error.log for details"
		echo ""
	fi
}



##############################################################################
# Print helpful message.
##############################################################################
optip() {
	tip "You can set it with the $1 option"
}


##############################################################################
# Print helpful message.
##############################################################################
tip() {
	if [  "$QUIET" != "true"  ]
	then
		helper "$1."
	fi
}



##############################################################################
# Print helpful message and exit.
##############################################################################
endtip() {
	if [  "$QUIET" != "true"  ]
	then
		helper "$1."
		echo ""
		exit
	fi
}



##############################################################################
# Print helpful message and exit.
##############################################################################
checklog() {
	if [  "$QUIET" != "true"  ]
	then
		endtip "Check error.log for details";
	fi
}



##############################################################################
# Pretty-print a log message.
##############################################################################
log() {
	if [  "$QUIET" != "true"  ]
	then
		MSG="$1"
		LINE="${GREEN}* ${NORMAL}${MSG}...";
		export LOGLINE=$LINE;
		echo -n $LINE
	fi
}



##############################################################################
# Pretty-print a helper message.
##############################################################################
helper() {
	if [  "$QUIET" != "true"  ]
	then
		MSG="$1"
		LINE="${BLUE}* ${NORMAL}${MSG}";
		export LOGLINE=$LINE;
		echo $LINE
		#yellow_ok
	fi
}



##############################################################################
# Pretty-print a prompt message.
##############################################################################
prompt () {
	if [  "$QUIET" != "true"  ]
	then
		MSG="$1"
		LINE="${PURPLE}*${NORMAL} ${BOLD}${MSG}${NORMAL}: ";
		export LOGLINE=$LINE;
		echo -n "$LINE"
		#yellow_ok
	fi
}



##############################################################################
# Pretty-print a warning message.
##############################################################################
warn() {
	if [  "$QUIET" != "true"  ]
	then
		MSG="$1"
		LINE="${YELLOW}*${NORMAL} ${BOLD}Warning: ${NORMAL}${MSG}.";
		export LOGLINE="${YELLOW}*${NORMAL}${BOLD}${NORMAL}${MSG}.";
		echo $LINE
		#warn_ok
	fi
}



##############################################################################
# Pretty-print an abort message.
##############################################################################
abort() {
	if [  "$QUIET" != "true"  ]
	then
		MSG="$1"
		LINE="${RED}*${NORMAL} ${BOLD}Abort: ${NORMAL}${MSG}!";
		export LOGLINE="${RED}*${NORMAL} ${BOLD}${NORMAL}${MSG}!";
		echo -n $LINE
		fail
	fi
}



##############################################################################
# Pretty-print an alert message.
##############################################################################
alert() {
	if [  "$QUIET" != "true"  ]
	then
		MSG="$1"
		LINE="${RED}*${NORMAL} ${BOLD}Alert: ${NORMAL}${MSG}!";
		export LOGLINE=$LINE;
		echo $LINE
	#red_ok
	fi
}




##############################################################################
# Using a LINE, print a status flag of the [  OK  ] variety.
##############################################################################
flag() {
	if [  "$QUIET" != "true"  ]
	then
		LINE=$1
		let COLS=$(tput cols)-${#LOGLINE}+${#LINE}
		printf "%${COLS}s\n" "$LINE"
	fi
}



##############################################################################
# Print [  OK  ] message.
##############################################################################
ok() {
	flag "[${BOLD}${GREEN}  OK  ${NORMAL}]"
}



##############################################################################
# Print [ FAIL ] message.
##############################################################################
fail() {
	flag "[${RED} FAIL ${NORMAL}]"
	success=0;
}



##############################################################################
# Print [  OK  ] message, in yellow.
##############################################################################
yellow_ok() {
	flag "[${GREEN}  OK  ${NORMAL}]"
}



##############################################################################
# Print [  OK  ] message, in red.
##############################################################################
red_ok() {
	flag "[${RED}  OK  ${NORMAL}]"
}


##############################################################################
# Print [ WARN ] message, in yellow.
##############################################################################
warn_ok () {
	flag "[${YELLOW} WARN ${NORMAL}]"
}
